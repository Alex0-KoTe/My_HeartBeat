print("Старт программы: Бегущий огонь (8 реле)")

-- Настройки эффекта
local step_delay = 200 -- Скорость бега огня (в миллисекундах)

while true do
    -- Проход вперед: от RL0 до RL7
    for i = 0, 7 do
        local relay = _G["RL" .. i]
        
        relay(1)       -- Включаем текущее реле
        delay(step_delay)
        relay(0)       -- Выключаем текущее реле
        
        wdt_feed()     -- Кормим WDT в каждой итерации цикла
    end
    
    -- Проход назад: от RL6 до RL1 (чтобы крайние реле не загорались дважды подряд)
    for i = 6, 1, -1 do
        local relay = _G["RL" .. i]
        
        relay(1)       -- Включаем текущее реле
        delay(step_delay)
        relay(0)       -- Выключаем текущее реле
        
        wdt_feed()     -- Кормим WDT в каждой итерации цикла
    end
end
