-- Функция задержки в миллисекундах (использует стандартный os.clock)
local function delay_ms(ms)
    local start_time = os.clock()
    -- Защита от переполнения или отсутствия os.clock
    if type(start_time) ~= "number" then
        -- Резервный вариант: простой цикл (примерно 1 сек при 160 МГц)
        for i = 1, 10000000 do end
        return
    end
    
    while (os.clock() - start_time) * 1000 < ms do
        -- Пустой цикл ожидания
    end
end

