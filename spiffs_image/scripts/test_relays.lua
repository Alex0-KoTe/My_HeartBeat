-- =========================================================
-- Тестовый скрипт для последовательного переключения реле
-- Файл: spiffs_image/scripts/test_relays.lua
-- =========================================================

print("========================================")
print(" ЗАПУСК ТЕСТА РЕЛЕ MCP23017 (Порт A) ")
print("========================================")

-- Проверяем, зарегистрированы ли функции управления реле
if type(RL0) ~= "function" then
    print("ОШИБКА: Функции управления реле (RL0-RL7) не найдены!")
    print("Проверьте инициализацию MCP23017 в main.c")
    return
end

print("Начинаем последовательное переключение...\n")

-- Функция безопасной задержки (не блокирует систему полностью)
local function delay_ms(ms)
    local target = os.clock() + (ms / 1000.0)
    while os.clock() < target do
        -- Короткий цикл, чтобы минимизировать нагрузку на планировщик FreeRTOS
        -- В чистом Lua без C-биндингов для vTaskDelay это лучший вариант
    end
end

for i = 0, 7 do
    local relay_func = _G["RL" .. i]
    
    if type(relay_func) == "function" then
        -- 1. Включаем реле
        print("[" .. i .. "] ВКЛЮЧАЕМ реле...")
        relay_func(1)
        
        -- 2. Пауза 1 секунда (1000 мс)
        delay_ms(1000)
        
        -- 3. Выключаем реле
        print("[" .. i .. "] ВЫКЛЮЧАЕМ реле...")
        relay_func(0)
        
        -- 4. Короткая пауза между реле для чёткости щелчков (300 мс)
        delay_ms(300)
    else
        print("ОШИБКА: Функция RL" .. i .. " не найдена!")
    end
end

print("\n========================================")
print(" ТЕСТ ЗАВЕРШЕН! Все 8 реле проверены.")
print("========================================")